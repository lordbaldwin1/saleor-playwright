#!/usr/bin/env node
/**
 * Ensures Saleor Docker containers can reach host-run apps (dummy payment app)
 * via host.docker.internal — required on Linux/CI; harmless on macOS.
 */
import { writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const platformDir = join(repoRoot, "saleor-platform");
const overridePath = join(platformDir, "docker-compose.override.yml");

if (!existsSync(platformDir)) {
  console.error("saleor-platform/ not found. Run: npm run setup");
  process.exit(1);
}

const content = `# Generated by saleor-e2e — do not edit manually.
# Lets API/worker containers call apps running on the host (dummy payment app).
# HTTP_IP_FILTER_ENABLED=False is required for local app install (Saleor docs).
services:
  api:
    extra_hosts:
      - "host.docker.internal:host-gateway"
    environment:
      - HTTP_IP_FILTER_ENABLED=False
  worker:
    extra_hosts:
      - "host.docker.internal:host-gateway"
    environment:
      - HTTP_IP_FILTER_ENABLED=False
`;

writeFileSync(overridePath, content);
console.log("Wrote saleor-platform/docker-compose.override.yml (host.docker.internal)");
